// Package choicegen writes the value lists the backend validates against (job
// statuses, work modes, comp options, setting choices…) as a TypeScript module,
// so the frontend imports them instead of keeping copies that drift.
package choicegen

import (
	"fmt"
	"strings"

	"jobtrack/internal/app"
	"jobtrack/internal/comp"
	"jobtrack/internal/marketdata"
	"jobtrack/internal/settings"
	"jobtrack/internal/taxes"
)

// OutputPath is the generated module, relative to the repository root.
const OutputPath = "frontend/src/generated/choices.ts"

type valueList struct {
	name, doc string
	values    []string
}

type constant struct {
	name, doc, value string
}

func valueLists() []valueList {
	return []valueList{
		{"STATUSES", "Pipeline stages, in board order.", app.JobStatuses},
		{"CLOSE_REASONS", "Why a job was closed.", app.CloseReasons},
		{"POSTING_TABS", "Discover's tabs, in display order.", app.PostingTabs},
		{"WORK_MODES", "How a job is worked (jobs, postings and match preferences).", settings.WorkModes},
		{"INTERVIEW_KINDS", "Kinds of real interview scheduled on a job.", app.ScheduledInterviewKinds},
		{"PACKAGE_KINDS", "Compensation package kinds.", comp.PackageKinds},
		{"EQUITY_TYPES", "Equity types in a package.", comp.EquityTypes},
		{"VESTINGS", "Vesting schedules.", comp.Vestings},
		{"FILING_STATUSES", "Federal filing statuses.", taxes.FilingStatuses},
		{"AI_PROVIDER_IDS", "Every AI provider a setting may name, in display order.", settings.AIProviderIDs},
		{"ANTHROPIC_EFFORTS", "Effort levels the Anthropic API accepts.", settings.AnthropicEfforts},
		{"MATCH_SENIORITY", "Target levels for job matching.", settings.MatchSeniorityOptions},
	}
}

func constants() []constant {
	return []constant{
		{"NATIONAL_AREA", "The market-data area code for remote / the whole United States.", marketdata.NationalArea},
		{"NO_PLAN_PROVIDER", "The plan provider value that starts a mock interview without a question plan.", app.PlanNone},
	}
}

// Render returns the generated module's full text.
func Render() string {
	var b strings.Builder
	b.WriteString("// Code generated by go generate (tools/choices); DO NOT EDIT.\n")
	b.WriteString("// Value lists the backend validates against. Labels for them live next to\n")
	b.WriteString("// their use (lib/format.ts, lib/comp.ts), keyed by these types.\n")
	for _, l := range valueLists() {
		quoted := make([]string, len(l.values))
		for i, v := range l.values {
			quoted[i] = tsString(v)
		}
		fmt.Fprintf(&b, "\n/** %s */\nexport const %s = [%s] as const\n", l.doc, l.name, strings.Join(quoted, ", "))
	}
	b.WriteString("\n/** Answer modes for OpenAI-compatible servers, in the order Settings offers them. */\nexport const ANSWER_MODES = [\n")
	for _, c := range settings.AnswerModeChoices {
		fmt.Fprintf(&b, "  { id: %s, label: %s },\n", tsString(c.ID), tsString(c.Label))
	}
	b.WriteString("] as const\n")
	renderAITasks(&b)
	for _, c := range constants() {
		fmt.Fprintf(&b, "\n/** %s */\nexport const %s = %s\n", c.doc, c.name, tsString(c.value))
	}
	return b.String()
}

// renderAITasks writes the AI task registry: its groups in display order, then every task.
func renderAITasks(b *strings.Builder) {
	b.WriteString("\n/** AI task groups, in the order Settings → AI features shows them. */\nexport const AI_TASK_GROUPS = [\n")
	for _, g := range settings.AITaskGroups {
		fmt.Fprintf(b, "  { id: %s, label: %s },\n", tsString(g.ID), tsString(g.Label))
	}
	b.WriteString("] as const\n")
	b.WriteString("\n/** Every AI task and its group; Settings.aiFeatures is keyed by these ids. */\nexport const AI_TASKS = [\n")
	for _, t := range settings.AITasks {
		fmt.Fprintf(b, "  { id: %s, group: %s, label: %s },\n", tsString(t.ID), tsString(t.Group), tsString(t.Label))
	}
	b.WriteString("] as const\n")
}

// tsString quotes s as a single-quoted TypeScript string, matching the frontend's style.
func tsString(s string) string {
	return "'" + strings.NewReplacer(`\`, `\\`, `'`, `\'`, "\n", `\n`).Replace(s) + "'"
}
